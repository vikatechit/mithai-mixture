export const RATE_ROWS = RATE_GROUPS.flatMap(group =>
  group.items.map(([name, code, price, unit = 'kg']) => ({
    name,
    code,
    price,
    unit,
    group: group.title
  }))
)

function rateKey(name) {
  return String(name || '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .replace(/\s+/g, ' ')
}

