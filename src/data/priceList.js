const LOOKUP = new Map()
for (const row of RATE_ROWS) {
  const key = rateKey(row.name)
  if (!LOOKUP.has(key)) LOOKUP.set(key, row)
}

export function shopPriceFor(name) {
  const key = rateKey(name)
  const mapped = SHOP_ALIASES[key] || key
  const hit = LOOKUP.get(mapped) || LOOKUP.get(key)
  if (!hit) return null
  if (hit.unit === 'pc' && /badam milk/.test(mapped)) return { ...hit, unit: 'bottle' }
  return hit
}
